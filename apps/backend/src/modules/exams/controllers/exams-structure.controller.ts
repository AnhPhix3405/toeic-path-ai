import {
  Body,
  Controller,
  Delete,
  Get,
  Param,
  ParseIntPipe,
  ParseUUIDPipe,
  Post,
  Put,
  Query,
  UseGuards,
} from '@nestjs/common';
import { ApiTags } from '@nestjs/swagger';
import { CurrentUser } from '../../../common/decorators/current-user.decorator';
import { Roles } from '../../../common/decorators/roles.decorator';
import { UserRole } from '../../../common/enums/user-role.enum';
import { RolesGuard } from '../../../common/guards/roles.guard';
import { JwtAuthGuard } from '../../auth/guards/jwt-auth.guard';
import { PolicyThrottlerGuard } from '../../../common/rate-limit/guards/policy-throttler.guard';
import { ThrottlePolicy } from '../../../common/rate-limit/decorators/throttle-policy.decorator';
import type { AuthenticatedUser } from '../../../common/interfaces/authenticated-user.interface';
import {
  ApiAddQuestionsDoc,
  ApiAutoGenerateDoc,
  ApiConfigureSectionsDoc,
  ApiExamsStructureControllerDoc,
  ApiGetStructureDoc,
  ApiRemoveQuestionDoc,
  ApiReorderQuestionsDoc,
} from '../docs/exams-structure.doc';
import { ConfigureExamSectionsDto } from '../dto/request/configure-exam-sections.dto';
import { AddExamQuestionsDto } from '../dto/request/add-exam-questions.dto';
import { ReorderExamQuestionsDto } from '../dto/request/reorder-exam-questions.dto';
import { AutoGenerateExamDto } from '../dto/request/auto-generate-exam.dto';
import { ExamStructureResponseDto } from '../dto/response/exam-structure-response.dto';
import { ExamsStructureService } from '../services/exams-structure.service';

@ApiTags('Exam Structure')
@ApiExamsStructureControllerDoc()
@UseGuards(JwtAuthGuard, RolesGuard, PolicyThrottlerGuard)
@Roles(UserRole.TEACHER, UserRole.ADMIN)
@Controller('exams/:id')
export class ExamsStructureController {
  constructor(private readonly structureService: ExamsStructureService) {}

  @Post('sections')
  @ThrottlePolicy('examsMutate')
  @ApiConfigureSectionsDoc()
  async configureSections(
    @Param('id', new ParseUUIDPipe()) id: string,
    @Body() dto: ConfigureExamSectionsDto,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ExamStructureResponseDto> {
    return this.structureService.configureSections(id, dto, user);
  }

  @Get('structure')
  @ApiGetStructureDoc()
  async getStructure(
    @Param('id', new ParseUUIDPipe()) id: string,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ExamStructureResponseDto> {
    return this.structureService.getStructure(id, user);
  }

  @Post('questions')
  @ThrottlePolicy('examsMutate')
  @ApiAddQuestionsDoc()
  async addQuestions(
    @Param('id', new ParseUUIDPipe()) id: string,
    @Body() dto: AddExamQuestionsDto,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ExamStructureResponseDto> {
    return this.structureService.addQuestions(id, dto, user);
  }

  @Put('questions/reorder')
  @ThrottlePolicy('examsMutate')
  @ApiReorderQuestionsDoc()
  async reorderQuestions(
    @Param('id', new ParseUUIDPipe()) id: string,
    @Body() dto: ReorderExamQuestionsDto,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ExamStructureResponseDto> {
    return this.structureService.reorderQuestions(id, dto, user);
  }

  @Delete('questions/:questionId')
  @ThrottlePolicy('examsMutate')
  @ApiRemoveQuestionDoc()
  async removeQuestion(
    @Param('id', new ParseUUIDPipe()) id: string,
    @Param('questionId', new ParseUUIDPipe()) questionId: string,
    @Query('version', ParseIntPipe) version: number,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ExamStructureResponseDto> {
    return this.structureService.removeQuestion(id, questionId, version, user);
  }

  @Post('auto-generate')
  @ThrottlePolicy('examsMutate')
  @ApiAutoGenerateDoc()
  async autoGenerate(
    @Param('id', new ParseUUIDPipe()) id: string,
    @Body() dto: AutoGenerateExamDto,
    @CurrentUser() user: AuthenticatedUser,
  ): Promise<ExamStructureResponseDto> {
    return this.structureService.autoGenerate(id, dto, user);
  }
}
